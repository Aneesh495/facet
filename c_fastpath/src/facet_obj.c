#include "facet_mesh.h"
#include "facet_math.h"
#include "facet_obj.h"
#include <stdio.h>
#include <stdlib.h>

FacetMesh* facet_obj_read(const char* filepath) {
    FILE* f = fopen(filepath, "r");
    if (!f) return NULL;

    FacetMesh* m = facet_mesh_create(128, 256);
    char line[256];

    while (fgets(line, sizeof(line), f)) {
        if (line[0] == 'v' && line[1] == ' ') {
            double x, y, z;
            if (sscanf(line + 2, "%lf %lf %lf", &x, &y, &z) == 3) {
                facet_mesh_add_vertex(m, facet_vec3_create(x, y, z));
            }
        } else if (line[0] == 'f' && line[1] == ' ') {
            uint32_t i0, i1, i2;
            if (sscanf(line + 2, "%u %u %u", &i0, &i1, &i2) == 3) {
                // Wavefront OBJ is 1-indexed
                if (i0 > 0 && i1 > 0 && i2 > 0) {
                    facet_mesh_add_triangle(m, i0 - 1, i1 - 1, i2 - 1);
                }
            }
        }
    }

    fclose(f);
    facet_mesh_compute_normals(m);
    return m;
}

bool facet_obj_write(const FacetMesh* mesh, const char* filepath) {
    if (!mesh || !filepath) return false;
    FILE* f = fopen(filepath, "w");
    if (!f) return false;

    fprintf(f, "# Wavefront OBJ generated by Facet Verified CSG Engine\n");
    for (size_t i = 0; i < mesh->vertex_count; ++i) {
        FacetVec3 v = mesh->vertices[i];
        fprintf(f, "v %.6f %.6f %.6f\n", v.x, v.y, v.z);
    }

    for (size_t i = 0; i < mesh->index_count; i += 3) {
        fprintf(f, "f %u %u %u\n",
            mesh->indices[i] + 1,
            mesh->indices[i + 1] + 1,
            mesh->indices[i + 2] + 1
        );
    }

    fclose(f);
    return true;
}
